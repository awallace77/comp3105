class SmallCNN(nn.Module):
    def __init__(self, num_classes=10):
        super().__init__()
        self.conv1 = nn.Conv2d(3, 32, 3, padding=1)
        self.conv2 = nn.Conv2d(32, 64, 3, padding=1)
        self.conv3 = nn.Conv2d(64, 128, 3, padding=1)
        self.pool = nn.MaxPool2d(2, 2)
        self.fc1 = nn.Linear(128*8*8, 256)  # Adjusted for 64x64 input
        self.fc2 = nn.Linear(256, num_classes)

    def forward(self, x):
        x = F.relu(self.conv1(x))
        x = self.pool(x)
        x = F.relu(self.conv2(x))
        x = self.pool(x)
        x = F.relu(self.conv3(x))
        x = self.pool(x)
        x = x.view(x.size(0), -1)
        features = F.relu(self.fc1(x))
        logits = self.fc2(features)
        return logits, features

# ----------------------
# Compute stable centroids
# ----------------------
def update_centroids(features, labels, centroids, counts, momentum=0.9, num_classes=10):
    for c in range(num_classes):
        mask = (labels == c)
        if mask.sum() > 0:
            batch_mean = features[mask].mean(0)
            centroids[c] = momentum * centroids[c] + (1 - momentum) * batch_mean
            counts[c] += mask.sum()
    return centroids, counts

# ----------------------
# Training function
# ----------------------
def train_model(model, in_loader, out_loader, num_epochs=50, lr=1e-3, lambda_ood=0.2, margin=1.0):
    model.to(device)
    optimizer = optim.Adam(model.parameters(), lr=lr)
    scheduler = optim.lr_scheduler.StepLR(optimizer, step_size=20, gamma=0.5)
    criterion = nn.CrossEntropyLoss()

    num_classes = 10
    feat_dim = 256
    centroids = torch.zeros(num_classes, feat_dim).to(device)
    counts = torch.zeros(num_classes).to(device)

    for epoch in range(num_epochs):
        model.train()
        running_loss = 0.0
        out_iter = iter(out_loader)

        for images, labels in in_loader:
            images, labels = images.to(device), labels.to(device)

            try:
                x_out = next(out_iter)
            except StopIteration:
                out_iter = iter(out_loader)
                x_out = next(out_iter)
            x_out = x_out.to(device)

            optimizer.zero_grad()
            logits_in, feat_in = model(images)
            _, feat_out = model(x_out)

            # In-domain classification
            class_loss = criterion(logits_in, labels)

            # Update centroids
            with torch.no_grad():
                centroids, counts = update_centroids(feat_in, labels, centroids, counts)

            # OOD loss: push out-domain features away from centroids
            dists = torch.cdist(feat_out, centroids)
            min_dists, _ = dists.min(dim=1)
            ood_loss = F.relu(margin - min_dists).mean()

            loss = class_loss + lambda_ood * ood_loss
            loss.backward()
            optimizer.step()
            running_loss += loss.item()

        scheduler.step()
        print(f"[Epoch {epoch+1}/{num_epochs}] Loss: {running_loss/len(in_loader):.4f} LR: {scheduler.get_last_lr()[0]:.6f}")

    return model

